"""Turn the constant tables of mbelib / libaeroambe into Rust.

Run once against a checkout of https://github.com/jontio/libaeroambe:
    python scripts/gen_ambe_tables.py PATH/libaeroambe/mbelib-master > crates/decaero-ambe/src/tables.rs
The tables are data from mbelib (ISC licence, "mbelib Author") and from the
libaeroambe team's AMBE 4800x3600 work (MIT); see NOTICE.
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1])
WANT = {
    # name: (file, rust type, row length or None for a flat table)
    "AmbeAeroLmprbl": ("ambe4800x3600_const.h", "u8", 8),
    "B2Aero": ("ambe4800x3600_const.h", "f32", None),
    "bitalloc": ("ambe4800x3600_const.h", "u8", 56),
    "bitorder": ("ambe4800x3600_const.h", "u8", 130),
    "lookupoffset": ("ambe4800x3600_const.h", "usize", None),
    "fxlookup": ("ambe4800x3600_const.h", "f32", None),
    "dq_quantstep": ("ambe4800x3600_const.h", "f32", None),
    "dq_prba_mul": ("ambe4800x3600_const.h", "f32", None),
    "dq_prba_add": ("ambe4800x3600_const.h", "f32", None),
    "dq_hoc_mul": ("ambe4800x3600_const.h", "f32", 9),
    "dq_hoc_add": ("ambe4800x3600_const.h", "f32", 9),
    "Ws": ("mbelib_const.h", "f32", None),
    "hammingGenerator": ("ecc_const.h", "u32", None),
    "golayGenerator": ("ecc_const.h", "u32", None),
    "golayMatrix": ("ecc_const.h", "u32", None),
}
RUST = {"AmbeAeroLmprbl": "LMPRBL", "B2Aero": "B2_AERO", "bitalloc": "BIT_ALLOC",
        "bitorder": "BIT_ORDER", "lookupoffset": "LOOKUP_OFFSET", "fxlookup": "FX_LOOKUP",
        "dq_quantstep": "DQ_QUANT_STEP", "dq_prba_mul": "DQ_PRBA_MUL", "dq_prba_add": "DQ_PRBA_ADD",
        "dq_hoc_mul": "DQ_HOC_MUL", "dq_hoc_add": "DQ_HOC_ADD", "Ws": "WS",
        "hammingGenerator": "HAMMING_GENERATOR",
        "golayGenerator": "GOLAY_GENERATOR", "golayMatrix": "GOLAY_MATRIX"}

def strip(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)

print("// made by CasualArclamp")
print("//! Constant tables, generated by `scripts/gen_ambe_tables.py`: do not edit by hand.")
print("//!")
print("//! Source: mbelib (ISC, (C) 2010 mbelib Author) and the AMBE 4800x3600 tables of")
print("//! libaeroambe (MIT, (C) 2018 libaeroambe team). See NOTICE at the repository root.")
print("#![allow(clippy::excessive_precision, clippy::unreadable_literal, clippy::approx_constant)]")
print("#![cfg_attr(rustfmt, rustfmt_skip)]")
for name, (file, ty, row) in WANT.items():
    text = strip((src / file).read_text(encoding="utf-8", errors="replace"))
    m = re.search(r"const\s+(?:int|float)\s+" + name + r"\s*((?:\[[^\]]*\])+)\s*=\s*\{(.*?)\}\s*;", text, flags=re.S)
    assert m, name
    nums = re.findall(r"[-+]?(?:0x[0-9a-fA-F]+|\d+\.?\d*(?:[eE][-+]?\d+)?|\.\d+(?:[eE][-+]?\d+)?)", m.group(2))
    if ty == "f32":
        vals = [repr(float(n)) for n in nums]
    else:
        vals = [str(int(n, 0)) for n in nums]
    print()
    if row:
        assert len(vals) % row == 0, (name, len(vals), row)
        rows = len(vals) // row
        print(f"pub static {RUST[name]}: [[{ty}; {row}]; {rows}] = [")
        for r in range(rows):
            print("    [" + ", ".join(vals[r * row:(r + 1) * row]) + "],")
        print("];")
    else:
        print(f"pub static {RUST[name]}: [{ty}; {len(vals)}] = [")
        for i in range(0, len(vals), 12):
            print("    " + ", ".join(vals[i:i + 12]) + ",")
        print("];")
